/**
 * YouTube Transcript Fetcher — 4-Tier Fallback
 *
 * Fetches YouTube video transcripts using a cascading fallback strategy:
 *
 * Tier 1: InnerTube Web API — uses YouTube's internal Web client API.
 *         Free, no API key needed. Works for most public videos.
 *
 * Tier 2: InnerTube Android API — same InnerTube API but with Android
 *         client headers. Bypasses some geo/age restrictions.
 *         Free, no API key needed.
 *
 * Tier 3: HTML Page Parsing — fetches the YouTube watch page and extracts
 *         captionTracks from embedded player data. Free, no API key needed.
 *         Works when InnerTube endpoints are blocked or rate-limited.
 *
 * Tier 4: Supadata API — paid third-party service as a last resort.
 *         Requires SUPADATA_API_KEY environment variable.
 *         Only attempted if env var is set.
 *
 * All tiers return: { text, language, isAutoGenerated }
 *
 * Usage:
 *   ANTHROPIC_API_KEY=your_key npx tsx youtube-transcript.ts
 *
 * @module youtube-transcript
 */

import type {
  TranscriptResult,
  TranscriptTier,
  TranscriptFetchResult,
  CaptionSegment,
  InnerTubePlayerResponse,
  InnerTubeCaptionTrack,
} from "./types";

// --- Constants ---

const INNERTUBE_API_URL =
  "https://www.youtube.com/youtubei/v1/player?prettyPrint=false";

const WEB_CLIENT_CONTEXT = {
  client: {
    clientName: "WEB",
    clientVersion: "2.20240101.00.00",
    hl: "pl",
    gl: "PL",
  },
};

const ANDROID_CLIENT_CONTEXT = {
  client: {
    clientName: "ANDROID",
    clientVersion: "19.09.37",
    androidSdkVersion: 30,
    hl: "pl",
    gl: "PL",
  },
};

const ANDROID_USER_AGENT =
  "com.google.android.youtube/19.09.37 (Linux; U; Android 11) gzip";

const REQUEST_TIMEOUT_MS = 15_000;

// --- Helpers ---

/**
 * Extract video ID from a YouTube URL or return as-is if already an ID.
 */
export function extractVideoId(urlOrId: string): string {
  // Already a video ID (11 chars, alphanumeric + dash/underscore)
  if (/^[a-zA-Z0-9_-]{11}$/.test(urlOrId)) {
    return urlOrId;
  }

  const patterns = [
    /(?:youtube\.com\/watch\?v=)([a-zA-Z0-9_-]{11})/,
    /(?:youtu\.be\/)([a-zA-Z0-9_-]{11})/,
    /(?:youtube\.com\/embed\/)([a-zA-Z0-9_-]{11})/,
    /(?:youtube\.com\/shorts\/)([a-zA-Z0-9_-]{11})/,
  ];

  for (const pattern of patterns) {
    const match = urlOrId.match(pattern);
    if (match?.[1]) return match[1];
  }

  throw new Error(`Cannot extract video ID from: ${urlOrId}`);
}

/**
 * Fetch with timeout support.
 */
async function fetchWithTimeout(
  url: string,
  options: RequestInit = {},
  timeoutMs: number = REQUEST_TIMEOUT_MS
): Promise<Response> {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), timeoutMs);

  try {
    const response = await fetch(url, {
      ...options,
      signal: controller.signal,
    });
    return response;
  } finally {
    clearTimeout(timeout);
  }
}

/**
 * Select the best caption track from a list.
 * Prefers: manual Polish > manual English > auto Polish > auto English > first available.
 */
function selectBestTrack(
  tracks: InnerTubeCaptionTrack[]
): InnerTubeCaptionTrack | null {
  if (tracks.length === 0) return null;

  // Priority: manual PL > manual EN > auto PL > auto EN > first
  const isAuto = (t: InnerTubeCaptionTrack) => t.kind === "asr";

  const manualPl = tracks.find(
    (t) => t.languageCode === "pl" && !isAuto(t)
  );
  if (manualPl) return manualPl;

  const manualEn = tracks.find(
    (t) => t.languageCode === "en" && !isAuto(t)
  );
  if (manualEn) return manualEn;

  const autoPl = tracks.find((t) => t.languageCode === "pl" && isAuto(t));
  if (autoPl) return autoPl;

  const autoEn = tracks.find((t) => t.languageCode === "en" && isAuto(t));
  if (autoEn) return autoEn;

  return tracks[0];
}

/**
 * Fetch caption text from a caption track URL and join segments.
 */
async function fetchCaptionText(
  baseUrl: string
): Promise<string> {
  // Request JSON3 format for structured captions
  const url = `${baseUrl}&fmt=json3`;
  const response = await fetchWithTimeout(url);

  if (!response.ok) {
    throw new Error(`Caption fetch failed: ${response.status}`);
  }

  const data = (await response.json()) as {
    events?: { segs?: { utf8?: string }[] }[];
  };

  if (!data.events) {
    throw new Error("No caption events in response");
  }

  const segments: string[] = [];
  for (const event of data.events) {
    if (event.segs) {
      for (const seg of event.segs) {
        if (seg.utf8 && seg.utf8.trim() !== "\n") {
          segments.push(seg.utf8.trim());
        }
      }
    }
  }

  return segments.join(" ").replace(/\s+/g, " ").trim();
}

// --- Tier 1: InnerTube Web API ---

/**
 * Tier 1: Fetch transcript via InnerTube Web API.
 *
 * Uses YouTube's internal API with WEB client context.
 * Free, no API key required. Works for most public videos.
 *
 * @param videoId - YouTube video ID (11 characters)
 * @returns TranscriptResult or throws on failure
 */
async function tier1InnertubeWeb(
  videoId: string
): Promise<TranscriptResult> {
  const body = JSON.stringify({
    videoId,
    context: WEB_CLIENT_CONTEXT,
  });

  const response = await fetchWithTimeout(INNERTUBE_API_URL, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body,
  });

  if (!response.ok) {
    throw new Error(`InnerTube Web API returned ${response.status}`);
  }

  const data = (await response.json()) as InnerTubePlayerResponse;
  const tracks =
    data.captions?.playerCaptionsTracklistRenderer?.captionTracks;

  if (!tracks || tracks.length === 0) {
    throw new Error("No caption tracks available (Tier 1)");
  }

  const bestTrack = selectBestTrack(tracks);
  if (!bestTrack) {
    throw new Error("Could not select caption track (Tier 1)");
  }

  const text = await fetchCaptionText(bestTrack.baseUrl);

  return {
    text,
    language: bestTrack.languageCode,
    isAutoGenerated: bestTrack.kind === "asr",
  };
}

